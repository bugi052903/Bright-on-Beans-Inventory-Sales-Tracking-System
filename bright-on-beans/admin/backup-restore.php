// ─── Native SQL Dump Generator ──────────────────────────────────────────────
function generateDatabaseDump($pdo) {
    $priorityTables = [
        'users',
        'secret_questions',
        'ingredients',
        'products',
        'recipe_ingredients',
        'sales_transactions',
        'sales_items',
        'inventory_history',
        'inventory_adjustments'
    ];

    $allStmt = $pdo->query("SHOW FULL TABLES WHERE Table_Type = 'BASE TABLE'");
    $allTables = $allStmt->fetchAll(PDO::FETCH_COLUMN);
    $tables = array_unique(array_merge($priorityTables, $allTables));

    $sql = "-- ================================================================\n";
    $sql .= "-- Bright on Beans Coffee House - Database Backup\n";
    $sql .= "-- System: " . APP_NAME . "\n";
    $sql .= "-- Generated: " . date('Y-m-d h:i:s A') . "\n";
    $sql .= "-- Database: " . DB_NAME . "\n";
    $sql .= "-- Generated By: " . getCurrentUserName() . " (" . getCurrentUserRole() . ")\n";
    $sql .= "-- ================================================================\n\n";
    $sql .= "SET FOREIGN_KEY_CHECKS = 0;\n";
    $sql .= "SET SQL_MODE = \"NO_AUTO_VALUE_ON_ZERO\";\n";
    $sql .= "SET time_zone = \"+08:00\";\n\n";

    foreach ($tables as $table) {
        $sql .= "-- --------------------------------------------------------\n";
        $sql .= "-- Structure for table `{$table}`\n";
        $sql .= "-- --------------------------------------------------------\n";
        $sql .= "DROP TABLE IF EXISTS `{$table}`;\n";

        $createStmt = $pdo->query("SHOW CREATE TABLE `{$table}`");
        $createRow = $createStmt->fetch(PDO::FETCH_NUM);
        $sql .= $createRow[1] . ";\n\n";

        // Dump data
        $dataStmt = $pdo->query("SELECT * FROM `{$table}`");
        $rows = $dataStmt->fetchAll(PDO::FETCH_ASSOC);

        if (!empty($rows)) {
            $sql .= "-- Data for table `{$table}` (" . count($rows) . " rows)\n";
            $columns = array_keys($rows[0]);
            $colList = '`' . implode('`, `', $columns) . '`';

            $chunks = array_chunk($rows, 50);
            foreach ($chunks as $chunk) {
                $valLines = [];
                foreach ($chunk as $row) {
                    $escapedVals = [];
                    foreach ($row as $val) {
                        if ($val === null) {
                            $escapedVals[] = 'NULL';
                        } else {
                            $escapedVals[] = $pdo->quote($val);
                        }
                    }
                    $valLines[] = '(' . implode(', ', $escapedVals) . ')';
                }
                $sql .= "INSERT INTO `{$table}` ({$colList}) VALUES\n" . implode(",\n", $valLines) . ";\n";
            }
            $sql .= "\n";
        }
    }

    $sql .= "SET FOREIGN_KEY_CHECKS = 1;\n";
    $sql .= "-- ================================================================\n";
    $sql .= "-- Backup Completed at " . date('Y-m-d h:i:s A') . "\n";
    $sql .= "-- ================================================================\n";

    return $sql;
}

function restoreDatabaseDumpRaw($pdo, $sqlContent) {
    $pdo->exec("SET FOREIGN_KEY_CHECKS = 0;");

    try {
        $lines = explode("\n", $sqlContent);
        $query = '';
        $count = 0;

        foreach ($lines as $line) {
            $trimmed = trim($line);
            if ($trimmed === '' || strpos($trimmed, '--') === 0 || strpos($trimmed, '/*') === 0) {
                continue;
            }
            $query .= $line . "\n";
            if (substr(rtrim($trimmed), -1) === ';') {
                $pdo->exec($query);
                $query = '';
                $count++;
            }
        }

        if (trim($query) !== '') {
            throw new RuntimeException('The SQL dump ends with an incomplete statement.');
        }

        return $count;
    } finally {
        $pdo->exec("SET FOREIGN_KEY_CHECKS = 1;");
    }
}

function findForeignKeyViolations($pdo) {
    $stmt = $pdo->query("
        SELECT TABLE_NAME, CONSTRAINT_NAME, COLUMN_NAME, REFERENCED_TABLE_NAME, REFERENCED_COLUMN_NAME
        FROM information_schema.KEY_COLUMN_USAGE
        WHERE TABLE_SCHEMA = DATABASE()
          AND REFERENCED_TABLE_NAME IS NOT NULL
        ORDER BY TABLE_NAME, CONSTRAINT_NAME, ORDINAL_POSITION
    ");
    $constraints = [];

    foreach ($stmt->fetchAll(PDO::FETCH_ASSOC) as $column) {
        $key = $column['TABLE_NAME'] . '.' . $column['CONSTRAINT_NAME'];
        if (!isset($constraints[$key])) {
            $constraints[$key] = [
                'table' => $column['TABLE_NAME'],
                'name' => $column['CONSTRAINT_NAME'],
                'referenced_table' => $column['REFERENCED_TABLE_NAME'],
                'columns' => [],
            ];
        }
        $constraints[$key]['columns'][] = [
            'column' => $column['COLUMN_NAME'],
            'referenced_column' => $column['REFERENCED_COLUMN_NAME'],
        ];
    }

    $violations = [];
    foreach ($constraints as $constraint) {
        $quoteIdentifier = static function ($identifier) {
            return '`' . str_replace('`', '``', $identifier) . '`';
        };
        $conditions = [];
        foreach ($constraint['columns'] as $column) {
            $conditions[] = 'child.' . $quoteIdentifier($column['column'])
                . ' = parent.' . $quoteIdentifier($column['referenced_column']);
        }

        $firstColumn = $constraint['columns'][0];
        $sql = 'SELECT COUNT(*) FROM ' . $quoteIdentifier($constraint['table']) . ' child'
            . ' LEFT JOIN ' . $quoteIdentifier($constraint['referenced_table']) . ' parent'
            . ' ON ' . implode(' AND ', $conditions)
            . ' WHERE parent.' . $quoteIdentifier($firstColumn['referenced_column']) . ' IS NULL';
        foreach ($constraint['columns'] as $column) {
            $sql .= ' AND child.' . $quoteIdentifier($column['column']) . ' IS NOT NULL';
        }

        $orphanCount = (int)$pdo->query($sql)->fetchColumn();
        if ($orphanCount > 0) {
            $violations[] = $constraint['table'] . '.' . $constraint['name']
                . ' has ' . $orphanCount . ' row(s) referencing missing records in '
                . $constraint['referenced_table'];
        }
    }

    return $violations;
}

// ─── Native SQL Restore Engine ──────────────────────────────────────────────
function restoreDatabaseDump($pdo, $sqlContent) {
    $previousDatabase = generateDatabaseDump($pdo);

    try {
        $executedCount = restoreDatabaseDumpRaw($pdo, $sqlContent);
        $violations = findForeignKeyViolations($pdo);
        if (!empty($violations)) {
            throw new RuntimeException(
                'The backup contains broken relationships: ' . implode('; ', $violations)
            );
        }

        return $executedCount;
    } catch (Throwable $restoreError) {
        try {
            restoreDatabaseDumpRaw($pdo, $previousDatabase);
        } catch (Throwable $rollbackError) {
            throw new RuntimeException(
                'Restore failed: ' . $restoreError->getMessage()
                . ' Automatic recovery also failed: ' . $rollbackError->getMessage(),
                0,
                $restoreError
            );
        }

        throw new RuntimeException(
            'Restore failed: ' . $restoreError->getMessage()
            . ' The database was returned to its pre-restore state.',
            0,
            $restoreError
        );
    }
}

// ─── Handle Actions: Download Backup, Local Backup, Restore ─────────────────
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action'])) {
    requireCSRF();
    $action = $_POST['action'];

    if ($action === 'download_backup') {
        try {
            $dump = generateDatabaseDump($pdo);
            $filename = 'bright_on_beans_backup_' . date('Y-m-d_His') . '.sql';

            // Also save a copy in the backups directory for history
            if (is_dir($backupDir)) {
                @file_put_contents($backupDir . '/' . $filename, $dump);
            }

            // Trigger browser file download
            header('Content-Type: application/sql');
            header('Content-Disposition: attachment; filename="' . $filename . '"');
            header('Content-Length: ' . strlen($dump));
            header('Pragma: no-cache');
            header('Expires: 0');
            echo $dump;
            exit;
        } catch (Exception $e) {
            setFlashMessage('error', 'Backup failed: ' . $e->getMessage());
            header('Location: ' . BASE_URL . '/admin/backup-restore.php');
            exit;
        }
    }

    if ($action === 'restore_upload') {
        try {
            if (!isset($_FILES['backup_file']) || $_FILES['backup_file']['error'] !== UPLOAD_ERR_OK) {
                throw new Exception('Please select a valid .sql backup file to upload.');
            }

            $file = $_FILES['backup_file'];
            $ext = strtolower(pathinfo($file['name'], PATHINFO_EXTENSION));

            if ($ext !== 'sql') {
                throw new Exception('Invalid file type. Only .sql database backup files are permitted.');
            }

            $content = file_get_contents($file['tmp_name']);
            if (empty($content)) {
                throw new Exception('The uploaded file is empty.');
            }

            $executedCount = restoreDatabaseDump($pdo, $content);
            setFlashMessage('success', "Database successfully restored from '{$file['name']}'! Executed {$executedCount} SQL queries. All records are up to date.");
            header('Location: ' . BASE_URL . '/admin/backup-restore.php');
            exit;
        } catch (Exception $e) {
            setFlashMessage('error', 'Restore failed: ' . $e->getMessage());
            header('Location: ' . BASE_URL . '/admin/backup-restore.php');
            exit;
        }
    }

    if ($action === 'restore_saved') {
        try {
            $targetFile = basename($_POST['saved_filename'] ?? '');
            $fullPath = $backupDir . '/' . $targetFile;

            if (empty($targetFile) || !file_exists($fullPath)) {
                throw new Exception('Selected backup file not found.');
            }

            $content = file_get_contents($fullPath);
            $executedCount = restoreDatabaseDump($pdo, $content);
            setFlashMessage('success', "Database successfully restored from saved backup '{$targetFile}'! Executed {$executedCount} queries.");
            header('Location: ' . BASE_URL . '/admin/backup-restore.php');
            exit;
        } catch (Exception $e) {
            setFlashMessage('error', 'Restore failed: ' . $e->getMessage());
            header('Location: ' . BASE_URL . '/admin/backup-restore.php');
            exit;
        }
    }

    if ($action === 'delete_saved') {
        try {
            $targetFile = basename($_POST['saved_filename'] ?? '');
            $fullPath = $backupDir . '/' . $targetFile;

            if (!empty($targetFile) && file_exists($fullPath)) {
                unlink($fullPath);
                setFlashMessage('success', "Backup file '{$targetFile}' removed.");
            }
            header('Location: ' . BASE_URL . '/admin/backup-restore.php');
            exit;
        } catch (Exception $e) {
            setFlashMessage('error', 'Delete failed: ' . $e->getMessage());
            header('Location: ' . BASE_URL . '/admin/backup-restore.php');
            exit;
        }
    }
}

